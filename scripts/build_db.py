# id 计数器
_counters = {}
def gid(prefix):
    _counters[prefix] = _counters.get(prefix, 0) + 1
    return f"{prefix}{_counters[prefix]:03d}"

items = []
def add(name, aliases, category, subcategory, purine, prange, prep, sources, note=""):
    # level 自动判定
    if purine is None:
        level = "未知"
    elif purine < 75:
        level = "低"
    elif purine < 150:
        level = "中"
    elif purine <= 300:
        level = "高"
    else:
        level = "极高"
    prefix_map = {
        "谷薯类":"G","豆类及制品":"D","蔬菜类":"S","菌藻类":"J","水果类":"F",
        "坚果种子":"N","畜禽肉类":"C","水产类":"SH","蛋类":"E","奶类及制品":"M",
        "饮料":"Y","调味品":"T","加工食品":"P","其他":"Q"
    }
    p = prefix_map[category]
    items.append({
        "id": gid(p),
        "name": name,
        "aliases": aliases,
        "category": category,
        "subcategory": subcategory,
        "purine_mg_per_100g": purine,
        "purine_range": prange if prange else [purine, purine] if purine is not None else None,
        "level": level,
        "preparation": prep or "生重/可食部",
        "sources": sources,
        "note": note
    })

