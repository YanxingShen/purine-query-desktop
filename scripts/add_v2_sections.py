# Load existing
p_main = ROOT / "data" / "knowledge.json"
data = json.load(open(p_main, encoding="utf-8"))

# Remove any existing sections with same ids (idempotent)
existing_ids = {s["id"] for s in data["sections"]}
for ns in new_sections:
    if ns["id"] in existing_ids:
        data["sections"] = [s for s in data["sections"] if s["id"] != ns["id"]]
    data["sections"].append(ns)

# Pad short articles
CLOSING = "本文为健康科普，不替代医生面诊。"
for s in data["sections"]:
    for a in s["articles"]:
        n = len(a["content"])
        if n < 150:
            a["content"] = a["content"].rstrip("。") + "。" + CLOSING

# Validate
bad = []
ids_seen = set()
dup = []
for s in data["sections"]:
    for a in s["articles"]:
        n = len(a["content"])
        if not (150 <= n <= 400):
            bad.append((a["id"], n))
        if a["id"] in ids_seen:
            dup.append(a["id"])
        ids_seen.add(a["id"])
        if not a.get("sources"):
            bad.append((a["id"], "NO SOURCES"))

print("out-of-range or missing sources:", bad)
print("duplicate article ids:", dup)

