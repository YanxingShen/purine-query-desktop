def lvl(v):
    if v is None: return "未知"
    if v < 75: return "低"
    if v < 150: return "中"
    if v <= 300: return "高"
    return "极高"

# 找各前缀当前最大编号
def next_id(prefix):
    nums = []
    for it in db["items"]:
        iid = it["id"]
        if iid.startswith(prefix):
            # 排除更长前缀（如 S 不应匹配 SH）
            rest = iid[len(prefix):]
            # rest 必须是纯数字
            if rest.isdigit():
                nums.append(int(rest))
    return max(nums)+1 if nums else 1

_counters = {}
def nid(prefix):
    if prefix not in _counters:
        _counters[prefix] = next_id(prefix)
    else:
        _counters[prefix] += 1
    return f"{prefix}{_counters[prefix]:03d}"

added = []
def add(name, aliases, cat, sub, v, rng, prep, sources, note=""):
    if name in existing_names:
        return
    for a in aliases:
        if a in existing_aliases:
            return
    item = {
        "id": nid({"谷薯类":"G","豆类及制品":"D","蔬菜类":"S","菌藻类":"J","水果类":"F",
                   "坚果种子":"N","畜禽肉类":"C","水产类":"SH","蛋类":"E","奶类及制品":"M",
                   "饮料":"Y","调味品":"T","加工食品":"P","其他":"Q"}[cat]),
        "name": name, "aliases": aliases, "category": cat, "subcategory": sub,
        "purine_mg_per_100g": v,
        "purine_range": rng if rng else ([v,v] if v is not None else []),
        "level": lvl(v), "preparation": prep or "生重/可食部",
        "sources": sources, "note": note
    }
    db["items"].append(item)
    existing_names.add(name)
    added.append(item["id"]+" "+name)

